"""Package both board builds, or verify committed packages against fresh builds.

Run from the repository root after `python tools/project.py build`:
  python games/EmberHollow/tools/package_boards.py
  python games/EmberHollow/tools/package_boards.py --check

Legacy WeAct downloads are preserved. New downloads have explicit board paths.
"""
from pathlib import Path
import argparse
import hashlib
import json
import sys

GAME = Path(__file__).resolve().parents[1]
ROOT = GAME.parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import chgpack
from chcart import model, sources, zipio
from package import memory

PROFILES = [('weact-f8u6', 'ember'), ('rev0', 'ember-rev0')]


def inspect(device, environment, build_root):
    folder = build_root / '.pio/build' / environment
    metadata = json.loads((folder / 'chgame-build.json').read_text())
    image = (folder / 'firmware.bin').read_bytes()
    target = chgpack.target_of(device)
    if (metadata['board'], metadata['target_id'], metadata['app_origin'], metadata['save_pages']) != (device, target, 0x3000, 2):
        raise ValueError('Wrong board, origin or save reservation: ' + environment)
    if metadata['flash_bytes'] != len(image):
        raise ValueError('Stale build metadata: ' + environment)
    ram = memory(folder / 'firmware.elf')
    if not image or len(image) > 50432 or ram > 18416:
        raise ValueError('Image exceeds save-safe flash or SRAM budget: ' + environment)
    # Also validate the CHG generated by the actual builder, independently of
    # the release packaging path below.
    builder_chg = (folder / 'firmware.chg').read_bytes()
    header = chgpack.parse(builder_chg, target=target)
    if header['payload_bytes'] != len(image) or builder_chg[chgpack.HEADER_BYTES:chgpack.HEADER_BYTES + len(image)] != image:
        raise ValueError('Builder CHG does not match its binary: ' + environment)
    return image, {'board': device, 'target_id': f'0x{target:08X}', 'environment': environment,
                   'build_type': metadata['build_type'], 'flash_bytes': len(image),
                   'flash_budget_bytes': 50432, 'static_ram_bytes': ram,
                   'static_ram_budget_bytes': 18416, 'save_pages': 2,
                   'sha256': hashlib.sha256(image).hexdigest()}


def artifacts(build_root):
    version = json.loads((GAME / 'chgame.json').read_text())['version']
    if version not in (GAME / 'config.h').read_text():
        raise ValueError('Game version mismatch')
    picture = chgpack.picture_file(str(GAME / 'docs/cart.png'))
    output, builds, images = {}, [], {}
    for device, environment in PROFILES:
        image, release = inspect(device, environment, build_root)
        _, debug = inspect(device, environment + '-debug', build_root)
        if release['build_type'] != 'release' or debug['build_type'] != 'debug':
            raise ValueError('Release/debug profile mismatch')
        builds += [release, debug]
        images[device] = image
        packed = chgpack.pack(image, 'EMBER HOLLOW', author='Ember Hollow', version=version,
                             picture=picture, target=chgpack.target_of(device))
        chgpack.parse(packed, target=chgpack.target_of(device))
        if chgpack.read_picture(packed) != picture:
            raise ValueError('Cart picture round trip failed')
        other = 'rev0' if device == 'weact-f8u6' else 'weact-f8u6'
        try:
            chgpack.parse(packed, target=chgpack.target_of(other))
        except chgpack.ChgError:
            pass
        else:
            raise ValueError('Wrong-board CHG was accepted')
        output[f'sdcard/{device}/GAMES/EMBER.CHG'] = packed
        output[f'firmware/{device}/EmberHollow.bin'] = image
    if images['rev0'] == images['weact-f8u6']:
        raise ValueError('Board binaries unexpectedly identical; check the selected variant')
    for name, devices in [('EmberHollow-Rev0.chgame', ['rev0']),
                          ('EmberHollow-MultiBoard.chgame', ['rev0', 'weact-f8u6'])]:
        game = sources.from_sketch(GAME, images[devices[0]], device=devices[0])
        game.binaries = {device: images[device] for device in devices}
        cart = model.Cart(title=game.title, games=[game], version=game.version,
                          author=game.author, license=game.license)
        data = zipio.to_bytes(cart)
        loaded = zipio.load(data)
        if loaded.games[0].binaries != game.binaries:
            raise ValueError('Device/cart round trip failed: ' + name)
        output['cart/' + name] = data
    lock = ROOT / 'dependency-lock.json'
    revision = json.loads(lock.read_text())['chgame']['revision'] if lock.is_file() else 'unrecorded (existing CHGame checkout)'
    report = {'game': 'Ember Hollow', 'version': version,
              'dependency_revision': revision,
              'application_origin': '0x00003000', 'hardware_tested': False,
              'save_magic': 'EHLO', 'save_version': 1, 'save_record_bytes': 40,
              'target_frame_rate': 30, 'display_spi_hz': 12000000,
              'builds': builds, 'checks': {'builder_and_release_chg_headers_crc': 'passed',
              'opposite_board_rejection': 'passed', 'menu_picture_round_trip': 'passed',
              'single_and_multi_board_cart_round_trip': 'passed'},
              'limitations': ['No hardware upload or playtest', 'No measured physical frame rate or stack high-water mark',
                              'Future dependency updates require rebuilding and checking both boards']}
    output['BUILD_REPORT_BOARDS.json'] = (json.dumps(report, indent=2) + '\n').encode()
    lines = ['# Both-board build report', '',
             f'Ember Hollow {version} uses one game source for the original CHGame Rev0 and the WeAct F8U6 variant.', '',
             '| Board | Profile | Flash / save-safe budget | Static SRAM / budget |',
             '|---|---|---:|---:|']
    for build in builds:
        lines.append(f"| {build['board']} | {build['build_type']} | {build['flash_bytes']:,} / 50,432 B | {build['static_ram_bytes']:,} / 18,416 B |")
    lines += ['', 'Both targets use application origin `0x3000`, reserve two 256-byte save pages, and keep the version-1, 40-byte EHLO save record. Static SRAM includes RAM-resident code; the budget reserves the retained 16-byte boot block and 2 KB stack.', '',
              'Rev0 selects the upstream `CHGame_Rev0` variant, CH32X035G8U chip definition, and CX35 target (`0x35335843`). WeAct selects `CHGame_WeActF8U6`, CH32X035F8U, and WF86 (`0x36384657`).', '',
              'The package checker validates each builder CHG and release CHG, payload CRC, visual-menu picture, wrong-board rejection, and both the Rev0-only and combined carts. CI rebuilds all four profiles and compares these packages with the committed files.', '',
              'Shared gameplay, save/restart, story, endings, five-second exit, and deterministic rendering are covered by the simulator checks. Board-specific wiring and electrical timing require a real console.', '',
              '**No hardware upload or playtest was performed.** The 30 Hz frame rate and 12 MHz display clock are configuration values, not measured performance.', '',
              'Dependency: `' + report['dependency_revision'] + '`. PlatformIO 6.1.19, pinned WCH RISC-V GCC 8.2, `-Os` and LTO.']
    output['BUILD_REPORT_BOARDS.md'] = ('\n'.join(lines) + '\n').encode()
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Compare outputs without writing them')
    parser.add_argument('--build-root', type=Path, default=ROOT, help='Project containing .pio/build')
    args = parser.parse_args()
    output = artifacts(args.build_root)
    for name, data in output.items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit('Package differs from fresh build: ' + name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(('Verified' if args.check else 'Wrote and verified') + f' {len(output)} board-specific artifacts; both targets reject the other board\'s CHG.')

if __name__ == '__main__':
    main()
